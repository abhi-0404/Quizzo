import { memo, useCallback, useMemo, useState } from "react";
import ReactMarkdown from "react-markdown";
import remarkGfm from "remark-gfm";
import remarkMath from "remark-math";
import rehypeKatex from "rehype-katex";
import rehypeSanitize, { defaultSchema } from "rehype-sanitize";
import { Highlight, themes } from "prism-react-renderer";
import { Check, Copy } from "lucide-react";
import type { QuestionAsset } from "@/data/questions";

/**
 * The single rendering surface for every question stem, option and passage.
 *
 * Pipeline (order matters):
 *   remark-gfm    → tables, task lists, strikethrough
 *   remark-math   → `$…$` / `$$…$$` into math nodes
 *   rehype-sanitize → strips untrusted HTML *before* KaTeX runs
 *   rehype-katex  → renders the math nodes
 *
 * Sanitising *before* KaTeX is deliberate: authored HTML is scrubbed while it
 * is still plain, and the only unsanitised markup that survives is KaTeX's own
 * output, generated by us from the LaTeX source (never author-supplied HTML).
 * Sanitising after KaTeX would instead force us to whitelist its entire MathML
 * and SVG surface, which is a far larger hole.
 *
 * Performance: memoised on `content`, and the plugin arrays are module-level
 * constants so they are not re-created per render — both matter on low-end
 * devices where these lists would otherwise invalidate the markdown tree.
 */

/** Allow the class names remark-math and fenced code rely on. */
const schema = {
  ...defaultSchema,
  attributes: {
    ...defaultSchema.attributes,
    span: [...(defaultSchema.attributes?.span ?? []), ["className"]],
    div: [...(defaultSchema.attributes?.div ?? []), ["className"]],
    code: [...(defaultSchema.attributes?.code ?? []), ["className"]],
    pre: [...(defaultSchema.attributes?.pre ?? []), ["className"]],
  },
};

const REMARK_PLUGINS = [remarkGfm, remarkMath];
const REHYPE_PLUGINS = [[rehypeSanitize, schema], rehypeKatex] as never;

/* ── Fenced code block: VS Code Dark + flat copy button ──────────────────── */

const CodeBlock = memo(function CodeBlock({ code, language }: { code: string; language: string }) {
  const [copied, setCopied] = useState(false);

  const copy = useCallback(() => {
    navigator.clipboard?.writeText(code).then(
      () => {
        setCopied(true);
        window.setTimeout(() => setCopied(false), 1400);
      },
      () => setCopied(false)
    );
  }, [code]);

  return (
    <div className="my-3 overflow-hidden rounded-md border border-border">
      <div className="flex items-center justify-between border-b border-border bg-[#252526] px-3 py-1.5">
        <span className="font-mono text-[11px] uppercase tracking-[0.08em] text-gray-400">
          {language || "code"}
        </span>
        <button
          type="button"
          onClick={copy}
          aria-label="Copy code"
          className="inline-flex items-center gap-1.5 rounded border border-[#3C3C3C] bg-[#2D2D2D] px-2 py-0.5 text-[11px] font-medium text-gray-300 hover:bg-[#3C3C3C] transition-colors"
        >
          {copied ? <Check className="h-3 w-3" /> : <Copy className="h-3 w-3" />}
          {copied ? "Copied" : "Copy"}
        </button>
      </div>
      <Highlight theme={themes.vsDark} code={code} language={language || "text"}>
        {({ className, style, tokens, getLineProps, getTokenProps }) => (
          <pre
            className={`ghost-scroll ${className} m-0 overflow-x-auto px-3 py-2.5 font-mono text-[12.5px] leading-relaxed`}
            style={{ ...style, backgroundColor: "#1E1E1E" }}
          >
            {tokens.map((line, i) => (
              <div key={i} {...getLineProps({ line })}>
                {line.map((token, k) => (
                  <span key={k} {...getTokenProps({ token })} />
                ))}
              </div>
            ))}
          </pre>
        )}
      </Highlight>
    </div>
  );
});

/* ── Element overrides — flat, solid, no shadows ─────────────────────────── */

const COMPONENTS = {
  code({ className, children, ...props }: any) {
    const match = /language-(\w+)/.exec(className ?? "");
    const text = String(children ?? "").replace(/\n$/, "");
    // Fenced blocks carry a language class; anything else is inline code.
    if (match) return <CodeBlock code={text} language={match[1]} />;
    return (
      <code
        className="rounded border border-border bg-muted px-1 py-0.5 font-mono text-[0.9em]"
        {...props}
      >
        {children}
      </code>
    );
  },
  // CodeBlock renders its own <pre>; avoid the extra wrapper.
  pre({ children }: any) {
    return <>{children}</>;
  },
  table({ children }: any) {
    return (
      <div className="ghost-scroll my-3 overflow-x-auto rounded-md border border-border">
        <table className="w-full border-collapse text-[13px]">{children}</table>
      </div>
    );
  },
  thead({ children }: any) {
    return <thead className="bg-muted">{children}</thead>;
  },
  th({ children }: any) {
    return <th className="border-b border-border px-3 py-2 text-left font-medium">{children}</th>;
  },
  td({ children }: any) {
    return <td className="border-b border-border px-3 py-2">{children}</td>;
  },
  ul({ children }: any) {
    return <ul className="my-2 list-disc space-y-1 pl-5">{children}</ul>;
  },
  ol({ children }: any) {
    return <ol className="my-2 list-decimal space-y-1 pl-5">{children}</ol>;
  },
  blockquote({ children }: any) {
    return (
      <blockquote className="my-3 border-l-2 border-border bg-muted px-3 py-2">{children}</blockquote>
    );
  },
  a({ children, href }: any) {
    return (
      <a href={href} target="_blank" rel="noopener noreferrer" className="underline underline-offset-2">
        {children}
      </a>
    );
  },
  hr() {
    return <hr className="my-4 border-t border-border" />;
  },
  // Paragraphs stay tight so a one-line stem does not gain stray margins.
  p({ children }: any) {
    return <p className="my-1 first:mt-0 last:mb-0 leading-relaxed">{children}</p>;
  },
  // Without an asset list there is nothing an image reference can resolve to.
  img() {
    return null;
  },
};

export interface UniversalRendererProps {
  content: string;
  className?: string;
  /**
   * Figures this content may reference as `![alt](asset-<id>)`.
   *
   * Resolution happens here rather than by inlining the data URL into the
   * markdown, so the sanitiser never has to allow the `data:` protocol and a
   * reference that does not match a known asset renders as nothing at all.
   */
  assets?: QuestionAsset[];
}

function UniversalRendererImpl({ content, className = "", assets }: UniversalRendererProps) {
  // Trimming here keeps a trailing newline from adding an empty paragraph.
  const value = useMemo(() => (content ?? "").replace(/\s+$/, ""), [content]);

  const components = useMemo(() => {
    if (!assets?.length) return COMPONENTS;
    return {
      ...COMPONENTS,
      img({ src, alt }: { src?: string; alt?: string }) {
        const asset = assets.find((a) => src === `asset-${a.id}`);
        if (!asset) return null;
        return (
          <img
            src={asset.src}
            alt={alt || asset.alt}
            /* Figures are cropped with a transparent background so they sit on
               the page colour instead of a white block. That leaves dark ink
               invisible on the dark theme, so it is inverted there — with the
               hue rotated back, which keeps coloured plots recognisable. */
            className="my-2 max-w-full dark:invert dark:hue-rotate-180"
          />
        );
      },
    };
  }, [assets]);

  if (!value) return null;

  return (
    <div className={`universal-content ${className}`}>
      <ReactMarkdown
        remarkPlugins={REMARK_PLUGINS}
        rehypePlugins={REHYPE_PLUGINS}
        components={components}
      >
        {value}
      </ReactMarkdown>
    </div>
  );
}

export const UniversalRenderer = memo(UniversalRendererImpl);
